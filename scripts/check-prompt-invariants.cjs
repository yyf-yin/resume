const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { loadSource, root, dir, read, save, hash } = require('./prompt-eval.cjs');
const load = loadSource(root);
const prompts = load('src/lib/ai/prompts.ts');
const questions = Array.from({ length: 11 }, (_, i) => ({ question: 'q' + i, suggestedAnswer: 'a', evidenceNeeded: [] }));
const prep = { likelyQuestions: questions, evidenceToPrepare: ['e'], possibleExaggerations: [], dataToSupplement: [], selfIntroduction: 'intro' };
const normalized = prompts.normalizeInterviewPrep(prep);
assert.equal(normalized.likelyQuestions.length, 10);
assert.equal(normalized.likelyQuestions[9].question, 'q9');
assert.equal(questions.length, 11);
assert.equal(normalized.selfIntroduction, 'intro');
assert.equal(prompts.normalizeInterviewPrep({ ...prep, likelyQuestions: questions.slice(0, 3) }).likelyQuestions.length, 3);
const input = read(path.join(dir, 'cases.json'))[2].input;
const answer = { id: 'q', question: 'test', purpose: 'test', userAnswer: '真实补充：只完成规划，不曾上线', generatedBullet: '' };
assert.ok(prompts.buildFinalResumeScorePrompt(input, {}, { dimensionScores: [] }, [answer]).includes(answer.userAnswer));
assert.ok(prompts.buildTargetingContext().includes('没有可复用'));
assert.ok(!prompts.buildAnalyzeCorePrompt(input).includes(input.originalResume));
const manifest = read(path.join(dir, 'baseline/manifest.json'));
assert.equal(hash(fs.readFileSync(path.join(root, 'src/lib/ai/score-policy.ts'))), manifest.files['src/lib/ai/score-policy.ts']);
const originalPrompts = fs.readFileSync(path.join(dir, 'baseline/src/lib/ai/prompts.ts.snapshot'), 'utf8');
const currentPrompts = fs.readFileSync(path.join(root, 'src/lib/ai/prompts.ts'), 'utf8');
const rubric = source => source.match(/const MATCH_SCORE_RUBRIC = `([\s\S]*?)`;/)[1].replaceAll('\r\n', '\n');
assert.equal(rubric(currentPrompts), rubric(originalPrompts));
const score = load('src/lib/ai/score-policy.ts').applyOptimizedScoreFloor;
for (const [before, after, expected] of [[45, 43, 50], [65, 60, 68], [65, 71, 71], [85, 80, 85], [65, NaN, 68]]) assert.equal(score(before, after), expected);
const checks = ['面试超量保留前10条', '不改动输入数组', '保留自我介绍与准备资料', '题目不足时不编造补齐', '评分接收真实追问回答', '旧请求无画像兼容', 'JD画像不读取原始简历以改变招聘标准', '评分兜底源码与基线完全一致', '既有评分边界行为保留'];
save(path.join(dir, 'invariant-checks.json'), { passed: checks, checkedAt: new Date().toISOString() });
console.log('Passed ' + checks.length + ' invariant checks.');
